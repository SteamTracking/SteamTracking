/**
 * Returns the strings that may be hashed into chunk ids: each path as listed and with ../ in front,
 * with {language} replaced by every language, and the bare name of each file with and without .css.
 */
function ExpandPaths(): string[] {
	const expanded = new Set<string>();

	for (const path of paths) {
		if (path.includes("{language}")) {
			for (const language of languages) {
				const localizedPath = path.replace("{language}", language);
				expanded.add(localizedPath);
				expanded.add(`../${localizedPath}`);
			}
			continue;
		}

		expanded.add(path);
		expanded.add(`../${path}`);

		if (path.includes("/")) {
			const fileName = path.slice(path.lastIndexOf("/") + 1);
			const name = fileName.replace(/(\.module)?\.[a-z]+$/, "");
			expanded.add(name);
			expanded.add(`${name}.css`);
		}
	}

	return [...expanded];
}

