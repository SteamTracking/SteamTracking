/**
 * Source paths of the `chunk~` files in the Steam web apps.
 *
 * A chunk file is named `chunk~` followed by the first 10 hex characters of the sha256 of the
 * source path of the chunk's main module, relative to the app's project folder, for example
 * sha256("src/localization/main_english.json"). `shared/`, `packages/` and `node_modules/` sit next
 * to the project folder, so their paths are hashed with `../` in front, for example
 * sha256("../shared/js/ui/greenenvelope.tsx") starts with ef6e72cfc2. Paths are listed without
 * `../` and expanded with and without it. Each path listed here is a real source file: its hash is a
 * chunk id seen in a build, its CSS module class names hash from it, or the file is named in the shipped
 * code. Add a path only after checking one of these. Paths that name no chunk still show which folders exist.
 *
 * Layout of the paths:
 * - `src/js/...` is the app's own code, `src/css/...` its styles, `src/localization/...` its strings.
 * - `shared/js/...`, `shared/css/...`, `shared/images/...` and `shared/localization/...` are shared between apps.
 * - `packages/<package>/src/...` are Valve's own packages, such as the generated protobufs.
 * - `node_modules/<package>/<file>` are libraries, using the file the package resolves to.
 * - File names are lowercase with their real extension, such as .ts, .tsx, .json, .css, .scss or .png.
 * - A chunk is named by its main module whether it is loaded with import() or only imported statically.
 * - Manual chunks hash their bare name, such as `libraries` or `modals`.
 * - A chunk that only holds css hashes `<name>.css`. The css of a js chunk reuses the js chunk id.
 *   The file name of each listed path is also tried bare and as `<name>.css`, so a bare name is
 *   listed only when its full path is unknown.
 * - An id with an 11th character is a 10 character id with a dedupe digit appended.
 * - `{language}` in a path stands for every language in languages.ts.
 *
 * Where to find candidates for an unknown id:
 * - An id that appears in several apps is a module from `shared/`, `packages/` or `node_modules/`.
 * - Localization imports keyed by path, such as `"../localization/main_english.json": () => import(...)`,
 *   give the path relative to the importing module.
 * - `chunkTemporaryNames` gives the file name the chunk had in older builds, matched by content.
 *   Folders are usually named after part of the file name, as in
 *   `src/js/ui/storeadmin/deadlines/deadlinelanding.tsx`, so try pieces of the name as folders under
 *   the folders already in this list, with each extension.
 * - CSS module class names are base64url(xxh64("<style path>\0<class name>")), cut to 11 characters
 *   and followed by `-`, with `_` in front when they start with a digit. The style path is the
 *   `.module.scss` file in the same form as the paths here, so the class objects in a chunk test a
 *   folder even for modules that are merged into another chunk.
 * - A chunk that bundles several modules is named after one of them, which may not be the one its
 *   temporary name comes from.
 * - Language chunks loaded through a per-language table, such as `x.english = () => import(...)`, get
 *   a different id in each app for the same file, so their hash input is not a plain path.
 */
